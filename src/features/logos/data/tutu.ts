// Coding key: row strings → 0/1/2/3 cells. "." = 0, "#" = 1, "o" = 2 (eye), "*" = 3 (accent).
const G = (rows: string[]): Grid =>
  rows.map((r) =>
    r.split('').map((c) => (c === '#' ? 1 : c === 'o' ? 2 : c === '*' ? 3 : 0)),
  ) as Grid;

