// frame helper: parse "row|row|row..." into a Grid
const F = (s: string): Grid => G(s.split('|'));
const FArr = (arr: ReadonlyArray<string | string[]>): Grid[] =>
  arr.map((x) => (typeof x === 'string' ? F(x) : G(x)));

