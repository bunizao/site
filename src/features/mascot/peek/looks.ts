function lookAsset(
  id: string,
  key: string,
  kind: 'expression' | 'costume',
  rows: ReadonlyArray<ReadonlyArray<number>>,
  summary: string,
  order: number,
): MascotAsset {
  return {
    id,
    mascot: 'peek',
    key,
    kind,
    label: key,
    summary,
    status: 'active',
    tags: [kind],
    grid: gridFromNumericRows(rows),
    palette: PEEK_LOOK_PALETTE,
    order,
  };
}

